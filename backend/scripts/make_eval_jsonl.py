"""Builds eval_images/eval_set.jsonl (max 20 samples, labels REAL / AI_GENERATED).

Sources: demo samples, 7 already-downloaded Commons AI images, the user's own phone photo and
Gemini image (from local scan previews), plus up to 7 real Commons photos (1280px thumbnails).
"""
import json
import shutil
import time
import urllib.parse
import urllib.request
from pathlib import Path

B = Path(__file__).resolve().parents[1]
EV = B / "eval_images"
SAMPLES = B.parent / "sample_images"
UA = "TruthLensHackathonEval/1.0 (educational model evaluation)"
rows = []


def add(src: Path, label: str, why: str, origin: str):
    dst = EV / src.name if src.parent == EV else EV / f"{len(rows):02d}_{src.name}"
    if src != dst:
        shutil.copyfile(src, dst)
    rows.append({"id": f"S{len(rows)+1:02d}", "file": dst.name, "label": label, "explanation": why, "source": origin})


for f, l, w in [("real_landscape_hopetoun_falls.jpg", "REAL", "Camera photo (Canon EOS 10D EXIF), Commons photographer Diliff."),
                ("real_portrait_armstrong.jpg", "REAL", "1969 NASA film portrait scan, public domain."),
                ("ai_stable_diffusion_comet.jpg", "AI_GENERATED", "Stable Diffusion img2img; prompt documented on Commons."),
                ("ai_artwork_mountains.jpg", "AI_GENERATED", "Uploader describes it as an AI-generated photo.")]:
    add(SAMPLES / f, l, w, "sample_images (demo)")

for f in ["ai_Images_generated_b_1.png", "ai_Images_generated_b_2.png", "ai_Images_generated_b_3.jpg",
          "ai_Images_generated_b_4.jpg", "ai_Images_generated_b_5.jpg"]:
    add(EV / f, "AI_GENERATED", "From Commons category 'Images generated by Stable Diffusion'.", "Wikimedia Commons")
for f in ["ai_Images_generated_b_0.png", "ai_Images_generated_b_1.jpg"]:
    add(EV / f, "AI_GENERATED", "From Commons category 'Images generated by DALL-E'.", "Wikimedia Commons")

# The user's own uploads (stored as metadata-stripped previews).
scans = B / "data" / "scans"
user = json.loads((EV / "user_uploads.json").read_text(encoding="utf-8-sig")) if (EV / "user_uploads.json").exists() else []
for u in user:
    p = scans / u["scan_id"] / "original.jpg"
    if p.exists():
        dst = EV / f"user_{u['scan_id']}.jpg"
        shutil.copyfile(p, dst)
        add(dst, u["label"], u["why"], "user upload (local only, not redistributable)")

# Real photos: one API call, 1280px standard thumbnails, spaced out.
need = 20 - len(rows)
q = urllib.parse.urlencode({"action": "query", "generator": "categorymembers", "gcmtitle": "Category:Quality images of people",
                            "gcmtype": "file", "gcmlimit": 25, "prop": "imageinfo", "iiprop": "url|mime|extmetadata",
                            "iiurlwidth": 1280, "format": "json"})
try:
    req = urllib.request.Request(f"https://commons.wikimedia.org/w/api.php?{q}", headers={"User-Agent": UA})
    pages = json.loads(urllib.request.urlopen(req, timeout=30).read())["query"]["pages"].values()
    for pg in pages:
        if need <= 0:
            break
        ii = pg["imageinfo"][0]
        if ii.get("mime") != "image/jpeg":
            continue
        time.sleep(3)
        try:
            data = urllib.request.urlopen(urllib.request.Request(ii["thumburl"], headers={"User-Agent": UA}), timeout=30).read()
        except Exception as e:  # noqa: BLE001
            print("skip", e)
            continue
        dst = EV / f"real_people_{need}.jpg"
        dst.write_bytes(data)
        lic = ii.get("extmetadata", {}).get("LicenseShortName", {}).get("value")
        add(dst, "REAL", f"Commons 'Quality images of people' (human-reviewed photo), {lic}.", ii.get("descriptionurl"))
        need -= 1
except Exception as e:  # noqa: BLE001
    print("commons unavailable:", e)

with open(EV / "eval_set.jsonl", "w", encoding="utf-8") as fh:
    for r in rows[:20]:
        fh.write(json.dumps(r, ensure_ascii=False) + "\n")
print(f"{len(rows[:20])} samples: {sum(r['label']=='REAL' for r in rows[:20])} REAL / "
      f"{sum(r['label']=='AI_GENERATED' for r in rows[:20])} AI_GENERATED -> {EV / 'eval_set.jsonl'}")

